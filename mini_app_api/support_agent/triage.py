def normalize(text: str) -> str:
    text = unicodedata.normalize("NFC", text or "")
    return re.sub(r"\s+", " ", text).strip().lower()


def _hits(low: str, keys: list[str]) -> list[str]:
    return [k for k in keys if k in low]


def detect_category(low: str) -> tuple[str, list[str]]:
    """Найкраща тема + усі спрацьовані ключі (для діагностики)."""
    scored: list[tuple[int, str]] = []
    all_hits: list[str] = []
    for cat, keys in CATEGORY_KEYWORDS.items():
        h = _hits(low, keys)
        if h:
            scored.append((len(h), cat))
            all_hits += [f"{cat}:{k}" for k in h]
    if not scored:
        return "other", all_hits
    # case_status і creditors важливіші за привітання, якщо збіглися разом
    priority = {"case_status": 3, "creditors": 3, "payment_ak": 2, "ecp_signature": 2,
                "documents": 2, "access_app": 2, "timing": 1, "greeting_thanks": 0}
    scored.sort(key=lambda s: (priority.get(s[1], 1), s[0]), reverse=True)
    return scored[0][1], all_hits


def is_question(low: str) -> bool:
    return "?" in low or low.startswith(_WORD_Q) or any(w in low for w in _WORD_Q)


@dataclass
class TriageOutcome:
    decision: Decision
    category: str
    confidence: float
    escalation: Optional[Escalation]
    signals: dict


def triage(msg: IncomingMessage, ctx: ClientContext, faq_hit: bool = False) -> TriageOutcome:
    """Детерміноване рішення. `faq_hit` — чи знайшлась заготовка в базі знань.

    Пріоритет правил (згори вниз, перше спрацьоване — вирішує):
      1. Розпач/самоушкодження → відповідаємо тепло + психолог, і прапор HIGH людині.
      2. Гнів/претензія/загроза → тільки жива людина (ESCALATE), бот не сперечається.
      3. Персональний статус справи без даних → ESCALATE (не вигадуємо факти).
      4. Юридичне судження під конкретику → ESCALATE.
      5. Довідкове/процесне/додаток/привітання → ANSWER (+ FLAG якщо тривожний тон).
    """
    low = normalize(msg.text)
    cat, cat_hits = detect_category(low)
    sig: dict = {"category": cat, "cat_hits": cat_hits}

    distress = _hits(low, DISTRESS)
    anger = _hits(low, ANGER)
    threat = _hits(low, THREAT)
    legal = _hits(low, LEGAL_JUDGMENT)
    creditor_pressure = cat == "creditors" or _hits(low, ["погрожуют", "погрозы", "дзвонят", "звонят"])
    sig.update(distress=distress, anger=anger, threat=threat,
               legal_judgment=legal, creditor_pressure=bool(creditor_pressure),
               is_question=is_question(low), has_media=msg.has_media)

    # 1) РОЗПАЧ — найвищий пріоритет: людяно відповісти + психолог + прапор HIGH.
    if distress:
        return TriageOutcome(
            Decision.ANSWER_AND_FLAG, "distress", 0.9,
            Escalation(to="психолог", reason="ознаки розпачу/емоційної кризи", priority="high"),
            sig)

    # 2) ГНІВ / ЗАГРОЗА / ПРЕТЕНЗІЯ — тільки жива людина.
    if anger or threat:
        return TriageOutcome(
            Decision.ESCALATE, "complaint", 0.85,
            Escalation(to="юрист", reason="претензія/недовіра/загроза — потрібна жива людина",
                       priority="high"),
            sig)

    # 3) ПЕРСОНАЛЬНИЙ СТАТУС СПРАВИ.
    if cat == "case_status":
        if ctx.known:
            # дані є — можемо відповісти, але тон майже завжди тривожний → підстрахуємось
            return TriageOutcome(Decision.ANSWER_AND_FLAG, cat, 0.7,
                                 Escalation(to="юрист",
                                            reason="питання про стан справи — тримаємо юриста в курсі",
                                            priority="normal"),
                                 sig)
        # даних нема — факти вигадувати не можна
        return TriageOutcome(Decision.ESCALATE, cat, 0.8,
                             Escalation(to="юрист",
                                        reason="статус конкретної справи, даних у агента нема",
                                        priority="normal"),
                             sig)

    # 4) ЮРИДИЧНЕ СУДЖЕННЯ під конкретну ситуацію.
    if legal:
        return TriageOutcome(Decision.ESCALATE, "legal_judgment", 0.8,
                             Escalation(to="юрист",
                                        reason="потрібне юридичне судження під конкретику справи",
                                        priority="normal"),
                             sig)

    # 5) ДОВІДКОВЕ / ПРОЦЕСНЕ / ДОДАТОК / ПРИВІТАННЯ — Аішка відповідає сама.
    answerable = {"documents", "ecp_signature", "payment_ak", "access_app",
                  "timing", "greeting_thanks"}
    if cat in answerable or faq_hit:
        # тиск кредиторів у процесному питанні → відповісти, але тримати юриста в курсі
        if creditor_pressure:
            return TriageOutcome(Decision.ANSWER_AND_FLAG, cat if cat != "other" else "creditors", 0.7,
                                 Escalation(to="юрист", reason="згадка про тиск кредиторів",
                                            priority="normal"),
                                 sig)
        base = 0.8 if faq_hit else 0.65
        if cat == "greeting_thanks" and not is_question(low):
            base = 0.85  # просте привітання/подяка — впевнено відповідаємо
        return TriageOutcome(Decision.ANSWER, cat, base, None, sig)

    # 6) Тиск кредиторів без чіткої теми — відповідаємо із заспокоєнням + прапор.
    if creditor_pressure:
        return TriageOutcome(Decision.ANSWER_AND_FLAG, "creditors", 0.65,
                             Escalation(to="юрист", reason="тиск кредиторів", priority="normal"),
                             sig)

    # 7) Невідома суть, але це питання → перестрахуємось людиною.
    if is_question(low) and len(low) > 12:
        return TriageOutcome(Decision.ESCALATE, "other", 0.5,
                             Escalation(to="юрист", reason="нетипове питання поза базою знань",
                                        priority="normal"),
                             sig)

    # 8) Дрібна репліка (ок/добре/фото без тексту) — легка відповідь.
    return TriageOutcome(Decision.ANSWER, "smalltalk", 0.6, None, sig)
